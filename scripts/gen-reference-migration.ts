/**
 * Generates the reference-data migration (catalog versions, dish ids, policy versions) for the
 * current catalog, so every dish/policy id stored in the database is validated by a foreign key.
 *
 *   npm run db:reference            # writes supabase/migrations/<stamp>_reference_<catalog>.sql
 *
 * Re-run after each catalog version bump (a unit test fails if the current catalog has no migration).
 * Upserts only: catalog rows are never deleted when personal data is deleted (ETD §4.6).
 */
import { readdirSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { loadCatalog } from "../src/catalog/index.ts";
import { POLICY_IDS, getPolicy } from "../src/engine/policy.ts";

/** Catalog versions that may appear in on-device history. */
const KNOWN_VERSIONS = ["catalog-v0.1-draft", "catalog-v0.2-draft", "catalog-v0.3-draft", "catalog-v0.4-draft", "catalog-v0.5-draft"];

const q = (s: string) => `'${s.replaceAll("'", "''")}'`;

export function referenceSql(): string {
  const catalog = loadCatalog();
  const versions = [...new Set([...KNOWN_VERSIONS, catalog.catalogVersion])];
  const lines: string[] = [
    `-- GENERATED by scripts/gen-reference-migration.ts for ${catalog.catalogVersion}. Do not edit by hand.`,
    "insert into public.catalog_versions(id, status) values",
    versions.map((v) => `  (${q(v)}, ${q(v === catalog.catalogVersion ? catalog.status : "retired")})`).join(",\n"),
    "on conflict (id) do update set status = excluded.status;",
    "",
    "insert into public.dish_variants(id, name, cuisine, first_catalog_version) values",
    catalog.dishes.map((d) => `  (${q(d.id)}, ${q(d.name)}, ${q(d.cuisine)}, ${q(catalog.catalogVersion)})`).join(",\n"),
    "on conflict (id) do update set name = excluded.name, cuisine = excluded.cuisine, updated_at = now();",
    "",
    "insert into public.policy_versions(id, config) values",
    POLICY_IDS.map((id) => `  (${q(id)}, ${q(JSON.stringify(getPolicy(id)))}::jsonb)`).join(",\n"),
    "on conflict (id) do update set config = excluded.config;",
    "",
  ];
  return lines.join("\n");
}

export const migrationsDir = fileURLToPath(new URL("../supabase/migrations/", import.meta.url));

export function referenceFileName(catalogVersion: string): string | undefined {
  const tag = catalogVersion.replace(/[^a-z0-9]+/gi, "_");
  return readdirSync(migrationsDir).find((f) => f.endsWith(`_reference_${tag}.sql`));
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  const v = loadCatalog().catalogVersion;
  const existing = referenceFileName(v);
  // Always sorts after every existing migration (clock-independent).
  const last = Math.max(0, ...readdirSync(migrationsDir).map((f) => Number(f.slice(0, 14)) || 0));
  const stamp = String(last + 100);
  const name = existing ?? `${stamp}_reference_${v.replace(/[^a-z0-9]+/gi, "_")}.sql`;
  writeFileSync(migrationsDir + name, referenceSql());
  console.log(`✓ wrote supabase/migrations/${name}`);
}
